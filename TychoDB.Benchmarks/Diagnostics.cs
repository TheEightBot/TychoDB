using System;
using System.Collections.Generic;
using System.IO;
using System.Linq.Expressions;
using System.Text;
using System.Text.Json.Serialization.Metadata;
using System.Threading.Tasks;
using Microsoft.Data.Sqlite;
using TychoDB.Benchmarks.Benchmarks;

namespace TychoDB.Benchmarks;

#pragma warning disable CA2100 // Diagnostic harness: all SQL is fixed internal text or library-generated; nothing user-supplied.

/// <summary>
/// Evidence-gathering harness for the indexing analysis (`dotnet run -- diagnose`).
/// Produces the raw material for docs/indexing-analysis.md: the index DDL the
/// public API actually generates, EXPLAIN QUERY PLAN transcripts for the SQL the
/// filter/sort builders actually emit (via InternalsVisibleTo), database file
/// sizes per index configuration, and the partial-index bound-parameter spike
/// that decides the redesign's target shape.
///
/// TychoDB connections hold `locking_mode = EXCLUSIVE`, so every phase either
/// drives the Tycho public API or a direct inspection connection — never both at
/// once.
/// </summary>
internal static class Diagnostics
{
    private const string DbName = "tycho_diagnose.db";
    private const int SeedCountA = 25_000;
    private const int SeedCountB = 5_000;

    private static readonly string WorkDir = Path.Combine(Path.GetTempPath(), "tycho_diagnose");
    private static readonly string DbPath = Path.Combine(WorkDir, DbName);
    private static readonly string FullTypeNameA = typeof(TestClassA).FullName;

    public static async Task RunAsync()
    {
        if (Directory.Exists(WorkDir))
        {
            Directory.Delete(WorkDir, recursive: true);
        }

        Directory.CreateDirectory(WorkDir);

        Console.WriteLine("# TychoDB indexing diagnostics");
        Console.WriteLine();

        // ---- Phase A: seed via the public API, no user indexes ----
        await SeedDatabaseAsync();

        long sizeBaseline;
        using (var conn = OpenInspectionConnection())
        {
            Console.WriteLine($"SQLite version: {Scalar(conn, "SELECT sqlite_version()")}");
            Console.WriteLine();

            sizeBaseline = CompactAndMeasure(conn, "baseline (no user indexes)");
            DumpIndexDdl(conn, "Built-in schema indexes");
            RunQueryPlans(conn, "Query plans BEFORE user indexes");
        }

        // Release the inspection connection's pooled handle before Tycho
        // reopens the file in exclusive mode.
        SqliteConnection.ClearAllPools();

        // ---- Phase B: create user indexes through the real public API ----
        await CreateUserIndexesViaPublicApiAsync();

        using (var conn = OpenInspectionConnection())
        {
            DumpIndexDdl(conn, "Index DDL generated by the public CreateIndex API");
            long sizeBroken = CompactAndMeasure(conn, "with the 3 public-API indexes");
            Console.WriteLine($"Delta vs baseline: {FormatBytes(sizeBroken - sizeBaseline)}");
            Console.WriteLine();

            DumpTable(conn, "sqlite_stat1", "Planner statistics after Tycho dispose (PRAGMA optimize ran)");
            RunQueryPlans(conn, "Query plans WITH public-API indexes");

            // ---- Phase C: synthetic per-index cost + corrected shapes ----
            Console.WriteLine("## Synthetic index-cost comparison (single index on LongProperty)");
            Console.WriteLine();

            DropUserIndexes(conn);
            long sizeClean = CompactAndMeasure(conn, "after dropping user indexes");

            Execute(conn, "CREATE INDEX idx_broken ON JsonValue(FullTypeName, JSON_EXTRACT(Data, '$'))");
            long sizeBrokenSingle = CompactAndMeasure(conn, "broken shape: JSON_EXTRACT(Data, '$') [what the API creates for value types]");
            Console.WriteLine($"Broken index cost: {FormatBytes(sizeBrokenSingle - sizeClean)}");
            Console.WriteLine();
            Execute(conn, "DROP INDEX idx_broken");

            Execute(conn, "CREATE INDEX idx_corrected ON JsonValue(FullTypeName, CAST(JSON_EXTRACT(Data, '$.LongProperty') as NUMERIC))");
            long sizeCorrected = CompactAndMeasure(conn, "corrected shape: (FullTypeName, CAST(path as NUMERIC))");
            Console.WriteLine($"Corrected index cost: {FormatBytes(sizeCorrected - sizeClean)}");
            Console.WriteLine();

            RunQueryPlans(conn, "Query plans with CORRECTED numeric index (pre-ANALYZE)");
            Execute(conn, "ANALYZE");
            RunQueryPlans(conn, "Query plans with CORRECTED numeric index (post-ANALYZE)");
            Execute(conn, "DROP INDEX idx_corrected");
            Execute(conn, "DELETE FROM sqlite_stat1; ANALYZE sqlite_master");

            // ---- Phase D: partial-index bound-parameter spike ----
            Console.WriteLine("## Partial-index spike (decides Bucket 3 shape)");
            Console.WriteLine();
            Console.WriteLine("Index WHERE clause uses a literal type name; the query binds $fullTypeName as a parameter.");
            Console.WriteLine();

            Execute(conn, $"CREATE INDEX idx_partial_long ON JsonValue(Partition, CAST(JSON_EXTRACT(Data, '$.LongProperty') as NUMERIC)) WHERE FullTypeName = '{FullTypeNameA}'");
            Execute(conn, $"CREATE INDEX idx_partial_str ON JsonValue(Partition, JSON_EXTRACT(Data, '$.StringProperty')) WHERE FullTypeName = '{FullTypeNameA}'");

            RunQueryPlans(conn, "Query plans with PARTIAL indexes, $fullTypeName bound as parameter (pre-ANALYZE)");
            Execute(conn, "ANALYZE");
            RunQueryPlans(conn, "Query plans with PARTIAL indexes (post-ANALYZE)");

            long sizePartial = CompactAndMeasure(conn, "with the 2 partial indexes");
            Console.WriteLine($"Partial-pair cost: {FormatBytes(sizePartial - sizeClean)}");
            Console.WriteLine();

            // Aligned ORDER BY: what sorting could use if SortBuilder emitted JSON_EXTRACT.
            Console.WriteLine("### Aligned ORDER BY (synthetic: JSON_EXTRACT instead of Data ->>)");
            ExplainShape(
                conn,
                "sort-aligned-string",
                BuildBaseQuery() + "\nORDER BY\nJSON_EXTRACT(Data, '$.StringProperty') ASC\nLIMIT 50",
                new FilterParameters());
            Console.WriteLine();
        }

        Console.WriteLine("Diagnostics complete.");
    }

    // ---------- database construction via the public API ----------
    private static SystemTextJsonSerializer BuildSerializer()
        => new(
            jsonTypeSerializers: new Dictionary<Type, JsonTypeInfo>
            {
                [typeof(TestClassA)] = TestJsonContext.Default.TestClassA,
                [typeof(List<TestClassA>)] = TestJsonContext.Default.ListTestClassA,
                [typeof(TestClassB)] = TestJsonContext.Default.TestClassB,
            });

    private static async Task SeedDatabaseAsync()
    {
        var db = await new Tycho(WorkDir, BuildSerializer(), DbName, rebuildCache: true, requireTypeRegistration: false)
            .ConnectAsync();

        var listA = new List<TestClassA>(SeedCountA);
        for (int i = 0; i < SeedCountA; i++)
        {
            listA.Add(new TestClassA
            {
                StringProperty = $"Test String {i}",
                LongProperty = i,
                TimestampMillis = 123451234 + i,
            });
        }

        await db.WriteObjectsAsync(listA, x => x.StringProperty);

        // A second stored type shares the JsonValue table; it shows how much of
        // every non-partial index is spent on rows the index can never serve.
        var listB = new List<TestClassB>(SeedCountB);
        for (int i = 0; i < SeedCountB; i++)
        {
            listB.Add(new TestClassB
            {
                StringProperty = $"Other Type {i}",
                DoubleProperty = i * 0.5,
            });
        }

        await db.WriteObjectsAsync(listB, x => x.StringProperty);

        db.Dispose();

        // Tycho connections use locking_mode = EXCLUSIVE and pooling keeps the
        // disposed connection (and its lock) alive; release it so the
        // inspection connection can open the file.
        SqliteConnection.ClearAllPools();
    }

    private static async Task CreateUserIndexesViaPublicApiAsync()
    {
        var db = await new Tycho(WorkDir, BuildSerializer(), DbName, rebuildCache: false, requireTypeRegistration: false)
            .ConnectAsync();

        await db.CreateIndexAsync<TestClassA>(x => x.StringProperty, "str_prop");
        await db.CreateIndexAsync<TestClassA>(x => x.LongProperty, "long_prop");
        await db.CreateIndexAsync<TestClassA>(
            new Expression<Func<TestClassA, object>>[] { x => x.StringProperty, x => x.TimestampMillis },
            "str_ts");

        db.Dispose();
        SqliteConnection.ClearAllPools();
    }

    // ---------- query-shape generation via the library's own builders ----------
    private static string BuildBaseQuery() => Queries.SelectDataFromJsonValueWithFullTypeName;

    private static (string Sql, FilterParameters Parameters) BuildFilterQuery(Action<FilterBuilder<TestClassA>> configure)
    {
        var filter = FilterBuilder<TestClassA>.Create();
        configure(filter);

        var sb = new StringBuilder(BuildBaseQuery());
        var parameters = new FilterParameters();
        filter.Build(sb, BuildSerializer(), parameters);
        return (sb.ToString(), parameters);
    }

    private static (string Sql, FilterParameters Parameters) BuildSortQuery(Action<SortBuilder<TestClassA>> configure, int top)
    {
        var sort = SortBuilder<TestClassA>.Create();
        configure(sort);

        var sb = new StringBuilder(BuildBaseQuery());
        sort.Build(sb, BuildSerializer());
        sb.AppendLine().AppendLine(Queries.Limit(top));
        return (sb.ToString(), new FilterParameters());
    }

    private static void RunQueryPlans(SqliteConnection conn, string heading)
    {
        Console.WriteLine($"## {heading}");
        Console.WriteLine();

        var equalsString = BuildFilterQuery(f => f.Filter(FilterType.Equals, x => x.StringProperty, "Test String 12500"));
        ExplainShape(conn, "equals-string", equalsString.Sql, equalsString.Parameters);

        var equalsNumeric = BuildFilterQuery(f => f.Filter(FilterType.Equals, x => x.LongProperty, 12500L));
        ExplainShape(conn, "equals-numeric", equalsNumeric.Sql, equalsNumeric.Parameters);

        var rangeNumeric = BuildFilterQuery(f => f.Filter(FilterType.GreaterThan, x => x.LongProperty, 24900L));
        ExplainShape(conn, "range-numeric", rangeNumeric.Sql, rangeNumeric.Parameters);

        var contains = BuildFilterQuery(f => f.Filter(FilterType.Contains, x => x.StringProperty, "String 55"));
        ExplainShape(conn, "contains-string", contains.Sql, contains.Parameters);

        var sortString = BuildSortQuery(s => s.OrderBy(SortDirection.Ascending, x => x.StringProperty), 50);
        ExplainShape(conn, "sort-string-top50", sortString.Sql, sortString.Parameters);

        var sortNumeric = BuildSortQuery(s => s.OrderBy(SortDirection.Ascending, x => x.LongProperty), 50);
        ExplainShape(conn, "sort-numeric-top50", sortNumeric.Sql, sortNumeric.Parameters);

        Console.WriteLine();
    }

    private static void ExplainShape(SqliteConnection conn, string label, string sql, FilterParameters parameters)
    {
        using var command = conn.CreateCommand();
        command.CommandText = "EXPLAIN QUERY PLAN " + sql;
        command.Parameters.AddWithValue("$fullTypeName", FullTypeNameA);
        command.Parameters.AddWithValue("$partition", string.Empty);

        for (int i = 0; i < parameters.Count; i++)
        {
            command.Parameters.AddWithValue(
                FilterParameters.ParameterPrefix + i.ToString(System.Globalization.CultureInfo.InvariantCulture),
                parameters.Values[i] ?? (object)DBNull.Value);
        }

        Console.WriteLine($"### {label}");
        using var reader = command.ExecuteReader();
        while (reader.Read())
        {
            Console.WriteLine($"    {reader.GetString(reader.FieldCount - 1)}");
        }

        Console.WriteLine();
    }

    // ---------- inspection helpers ----------
    private static SqliteConnection OpenInspectionConnection()
    {
        var conn = new SqliteConnection($"Data Source={DbPath}");
        conn.Open();
        return conn;
    }

    private static void DumpIndexDdl(SqliteConnection conn, string heading)
    {
        Console.WriteLine($"## {heading}");
        Console.WriteLine();
        Console.WriteLine("```sql");

        using var command = conn.CreateCommand();
        command.CommandText = "SELECT name, sql FROM sqlite_master WHERE type = 'index' ORDER BY name";
        using var reader = command.ExecuteReader();
        while (reader.Read())
        {
            var sql = reader.IsDBNull(1) ? $"-- {reader.GetString(0)} (implicit autoindex)" : reader.GetString(1) + ";";
            Console.WriteLine(sql);
        }

        Console.WriteLine("```");
        Console.WriteLine();
    }

    private static void DumpTable(SqliteConnection conn, string table, string heading)
    {
        Console.WriteLine($"## {heading}");
        Console.WriteLine();

        using var command = conn.CreateCommand();
        command.CommandText = $"SELECT * FROM {table}";

        try
        {
            using var reader = command.ExecuteReader();
            bool any = false;
            while (reader.Read())
            {
                any = true;
                var parts = new string[reader.FieldCount];
                for (int i = 0; i < reader.FieldCount; i++)
                {
                    parts[i] = reader.IsDBNull(i) ? "NULL" : reader.GetValue(i).ToString();
                }

                Console.WriteLine($"    {string.Join(" | ", parts)}");
            }

            if (!any)
            {
                Console.WriteLine("    (empty)");
            }
        }
        catch (SqliteException e)
        {
            Console.WriteLine($"    (absent: {e.Message})");
        }

        Console.WriteLine();
    }

    private static long CompactAndMeasure(SqliteConnection conn, string label)
    {
        Execute(conn, "PRAGMA wal_checkpoint(TRUNCATE)");
        Execute(conn, "VACUUM");
        Execute(conn, "PRAGMA wal_checkpoint(TRUNCATE)");

        long size = new FileInfo(DbPath).Length;
        var walPath = DbPath + "-wal";
        if (File.Exists(walPath))
        {
            size += new FileInfo(walPath).Length;
        }

        Console.WriteLine($"File size — {label}: {FormatBytes(size)}");
        Console.WriteLine();
        return size;
    }

    /// <summary>
    /// Drops every user-created index (physical names carry a hash suffix, so they
    /// cannot be hard-coded here), leaving the built-in schema indexes in place.
    /// </summary>
    private static void DropUserIndexes(SqliteConnection conn)
    {
        var names = new List<string>();

        using (var command = conn.CreateCommand())
        {
            command.CommandText =
                "SELECT name FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL AND name NOT LIKE 'idx_jsonvalue%' AND name NOT LIKE 'idx_streamvalue%'";
            using var reader = command.ExecuteReader();
            while (reader.Read())
            {
                names.Add(reader.GetString(0));
            }
        }

        foreach (var name in names)
        {
            Execute(conn, $"DROP INDEX IF EXISTS {name}");
        }

        Execute(conn, "DELETE FROM TychoIndex");
    }

    private static void Execute(SqliteConnection conn, string sql)
    {
        using var command = conn.CreateCommand();
        command.CommandText = sql;
        command.ExecuteNonQuery();
    }

    private static object Scalar(SqliteConnection conn, string sql)
    {
        using var command = conn.CreateCommand();
        command.CommandText = sql;
        return command.ExecuteScalar();
    }

    private static string FormatBytes(long bytes)
        => bytes switch
        {
            >= 1024 * 1024 => $"{bytes / (1024.0 * 1024.0):F2} MiB ({bytes:N0} bytes)",
            >= 1024 => $"{bytes / 1024.0:F1} KiB ({bytes:N0} bytes)",
            _ => $"{bytes:N0} bytes",
        };
}
